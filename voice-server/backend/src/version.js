/**
 * 服务端版本号。
 *
 * ── 为什么需要它 ────────────────────────────────────────────
 * 在这之前服务端**根本没有版本号**，于是"服务器上跑的到底是哪一版代码"
 * 只能靠推断 —— 比如"systemctl 重启时间晚于文件改动时间"。
 * 那个证据链不够硬：scp 可能只传了一半，重启也可能是因为别的原因。
 *
 * 现在 `GET /health` 会直接给出 `serverVersion`，一眼就能确认。
 *
 * ── 版本号从哪来 ────────────────────────────────────────────
 * **就写在这一行**。改服务端代码时把它 +1。
 *
 * 为什么不去读 `backend/package.json`（那样能"单一来源"）：
 * 部署是**手工 scp 几个文件**的，万一漏传了 package.json，
 * 版本号会**显示旧值** —— 那比没有版本号更糟，因为会让人以为部署成功了。
 * 硬编码在这一个文件里，传了就是传了，没有中间状态。
 *
 * （`package.json` 里也有个 version，那个只给 npm 看，改的时候顺手一起改，
 *   运行时以这里为准。）
 *
 * ── 服务端版本独立于客户端 ──────────────────────────────────
 * 两边各自记各自的 —— 它们可以分别部署、也会分别回滚。
 *
 *   服务端改了什么    → 改下面这一行
 *   客户端改了什么    → 改 voice-client/package.json
 *   两边都改了        → 两边都改
 */

export const SERVER_VERSION = '1.4.1';
