/**
 * ⚠️ 加语言只要在这里加一项 ✗
 *    `Record<MsgKey, string>` 会立刻要求把那 35 个键都补上 ✓
 *    漏了编译不过 ✓ 不会出现"切过去一半是中文一半是空白" ✓
 */
export const LANGS = {
  'zh-CN': { label: '简体中文', dict: ZH },
  en: { label: 'English', dict: EN },
  ja: { label: '日本語', dict: JA },
  fr: { label: 'Français', dict: FR },
} as const

export type Lang = keyof typeof LANGS

export const DEFAULT_LANG: Lang = 'zh-CN'

export function isLang(v: unknown): v is Lang {
  return typeof v === 'string' && Object.prototype.hasOwnProperty.call(LANGS, v)
}

/**
 * 翻译函数的类型 ✓
 *
 * ⚠️ 导出来是为了**能往普通函数里传** ✗
 *    有些格式化函数（比如时间戳 ✓）不在组件里 ✓ 用不了 hook ✓
 *    只能把 `t` 当参数递进去 ✓ 那这里就需要一个类型 ✓
 */
export type TFn = (key: MsgKey, vars?: Record<string, string | number>) => string

/**
 * 查一条文案。
 *
 * `vars` 用来替换 `{name}` 这种占位符 ✓
 * ⚠️ 找不到的占位符**原样保留** ✗ —— 不要替换成空字符串 ✓
 *    那样界面上会凭空少一块 ✓ 而保留 `{n}` 至少一眼能看出是哪儿错了 ✓
 */
export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  // ⚠️ 这里理论上取不到 undefined ✗（MsgKey 是从 ZH 推出来的 ✓）
  //    但语言表是运行时选的 ✓ 加个兜底免得将来手滑改了结构就白屏 ✓
  const dict = LANGS[lang]?.dict ?? LANGS[DEFAULT_LANG].dict
  let text: string = dict[key] ?? ZH[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.split(`{${k}}`).join(String(v))
    }
  }
  return text
}

// ─────────────────────────────────────────────────────────────
// React 绑定
//
// ⚠️ 用 context 而不是模块级的"当前语言"变量 ✗
//    模块级变量改了**不会触发重渲染** ✓ 切语言得手动刷新页面才行 ✓
//    而 context 一变，所有用了 useT 的组件自动重渲染 ✓
//    （这也正是"换个语言要立刻生效"的前提 ✓）
// ─────────────────────────────────────────────────────────────

export const LangCtx = createContext<Lang>(DEFAULT_LANG)

/**
 * 改语言的入口 ✓
 *
 * ⚠️ 为什么不把"当前值 + 设置函数"塞进同一个 context ✗
 *    那样每次语言一变，**整个对象都是新的** ✓
 *    只想要设置函数的组件也会跟着重渲染 ✓
 *    拆成两个之后，设置函数是**稳定的** ✓（main.tsx 里 useCallback 稳住了 ✓）
 */
export const LangSetCtx = createContext<(lang: Lang) => void>(() => {})

/** 当前语言 ✓（设置面板里显示选中项要用 ✓） */
export function useLang(): Lang {
  return useContext(LangCtx)
}

/** 切语言的函数 ✓ 引用是稳定的 ✓ 可以放心写进依赖数组 ✓ */
export function useSetLang(): (lang: Lang) => void {
  return useContext(LangSetCtx)
}

/**
 * 取翻译函数 ✓
 *
 * ⚠️ 用 useCallback 稳住引用 ✗
 *    每次渲染返回一个新函数的话 ✓
 *    把它写进 useEffect / useMemo 依赖的地方会**每次都重跑** ✓
 */
export function useT(): (key: MsgKey, vars?: Record<string, string | number>) => string {
  const lang = useContext(LangCtx)
  return useCallback(
    (key: MsgKey, vars?: Record<string, string | number>) => translate(lang, key, vars),
    [lang]
  )
}

/** 语言选择的存放位置 ✓ 单独一个键 —— 不塞进 config 里 ✓ 免得动配置结构 ✓ */
export const LANG_STORAGE_KEY = 'voice.lang'

export function loadLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_STORAGE_KEY)
    return isLang(v) ? v : DEFAULT_LANG
  } catch {
    return DEFAULT_LANG
  }
}

export function saveLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_STORAGE_KEY, lang)
  } catch {
    /* 存不了就算了 ✓ 不影响这次会话用 ✓ */
  }
}
